  const FALLBACK = 'en';

  /** Best supported language from the browser preferences. */
  function detect() {
    const prefs = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || ''];
    for (const pref of prefs) {
      const base = String(pref).toLowerCase().split('-')[0];
      if (LANGUAGES[base]) return base;
    }
    return FALLBACK;
  }

  function t(lang, key) {
    const ui = (LANGUAGES[lang] || LANGUAGES[FALLBACK]).ui;
    return ui[key] !== undefined ? ui[key] : LANGUAGES[FALLBACK].ui[key];
  }

  function sheet(lang) {
    return (LANGUAGES[lang] || LANGUAGES[FALLBACK]).sheet;
  }

  const isRtl = (lang) => (LANGUAGES[lang] || {}).dir === 'rtl';

  HT.i18n = { languages: LANGUAGES, detect, t, sheet, isRtl };
